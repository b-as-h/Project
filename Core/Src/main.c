    /* 传感器定时读取（DHT11、DS18B20、光照、片内温度） */
    Sensor_Process();

    /* UI 处理（输入 + 刷新） */
    App_UI_Process();

    /* 处理业务事件 */
    App_UI_HandleEvents();

    /* 蓝牙命令解析与周期遥测 */

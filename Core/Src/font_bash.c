/**
 * @brief 在 zh16x16 表中查找 UTF-8 编码对应的索引
 */
static int Font_FindChineseIndex(const uint8_t *utf8_code)
{
    for (int i = 0; i < ZH16x16_COUNT; i++) {
        if (zh16x16[i][0] == utf8_code[0] &&
            zh16x16[i][1] == utf8_code[1] &&
            zh16x16[i][2] == utf8_code[2]) {
            return i;
        }
    }
    return -1;
}

/**
 * @brief 绘制单个 ASCII 字符（6x8 位图）
 */
void Font_DrawASCIIChar(int16_t x, int16_t y, char c)
{
    if (c < 32 || c > 127) return;
    uint8_t idx = (uint8_t)c - 32;
    const uint8_t *glyph = font_6x8_data[idx];

    for (int col = 0; col < 6; col++) {
        uint8_t byte = glyph[col];
        for (int row = 0; row < 8; row++) {
            if (byte & (1 << row)) {
                OLED_DrawPixel(x + col, y + row);
            }
        }
    }
}

/**
 * @brief 绘制单个中文字符（16x16 位图）
 */
void Font_DrawChineseChar(int16_t x, int16_t y, const uint8_t *utf8_code)
{
    int idx = Font_FindChineseIndex(utf8_code);
    if (idx < 0) return;

    const uint8_t *data = zh16x16[idx] + 3; /* 跳过 UTF-8 编码 */

    /* 绘制左半部分（8列 x 16行） */
    for (int col = 0; col < 8; col++) {
        uint8_t byte = data[col];
        for (int row = 0; row < 8; row++) {
            if (byte & (1 << row)) {
                OLED_DrawPixel(x + col, y + row);
            }
        }
        uint8_t byte2 = data[col + 8];
        for (int row = 0; row < 8; row++) {
            if (byte2 & (1 << row)) {
                OLED_DrawPixel(x + col, y + row + 8);
            }
        }
    }

    /* 绘制右半部分（8列 x 16行） */
    for (int col = 0; col < 8; col++) {
        uint8_t byte = data[16 + col];
        for (int row = 0; row < 8; row++) {
            if (byte & (1 << row)) {
                OLED_DrawPixel(x + 8 + col, y + row);
            }
        }
        uint8_t byte2 = data[16 + col + 8];
        for (int row = 0; row < 8; row++) {
            if (byte2 & (1 << row)) {
                OLED_DrawPixel(x + 8 + col, y + row + 8);
            }
        }
    }
}

